func buildTemplateData(module *spec.Module) (templateData, error) {
	data := templateData{
		SourceSpec:                   filepath.ToSlash(module.SourcePath),
		TemplateRevision:             backendTemplateRevision,
		FrontendTemplateRevision:     frontendV6TemplateRevision,
		DocsTemplateRevision:         docsTemplateRevision,
		E2ETemplateRevision:          e2eV6TemplateRevision,
		InstructionsTemplateRevision: instructionsTemplateRevision,
		ModuleName:                   module.Metadata.Name,
		EnvPrefix:                    strings.ToUpper(spec.SnakeCase(module.Metadata.Name)),
		Package:                      strings.ReplaceAll(spec.SnakeCase(module.Metadata.Name), "-", "_"),
		ModelName:                    module.Spec.Entity.GoName,
		DisplayName:                  escapeGoContent(module.Metadata.DisplayName),
		Description:                  escapeGoContent(module.Metadata.Description),
		Table:                        module.Spec.Entity.Table,
		MigrationID:                  module.Spec.Generation.MigrationID,
		AuthorizationMigrationID:     module.Spec.Generation.AuthorizationMigrationID,
		APIVersion:                   module.Spec.API.Version,
		APIBasePath:                  module.Spec.API.BasePath,
		FullAPIPath:                  "/admin/api" + module.Spec.API.BasePath,
		APIResource:                  strings.TrimPrefix(module.Spec.API.BasePath, "/"),
		AdminBypass:                  module.Spec.Ownership.AdminBypass != nil && *module.Spec.Ownership.AdminBypass,
		UIList:                       module.Spec.UI.List,
		UIForm:                       module.Spec.UI.Form,
		UIDetail:                     module.Spec.UI.Detail,
		UIMobile:                     module.Spec.UI.Mobile != nil && *module.Spec.UI.Mobile,
		UIExport:                     module.Spec.UI.Export,
		HasFrontendV6:                module.SupportsFrontendTarget(spec.FrontendTargetAntDV6),
		Menu: menuData{
			Name:                       escapeGoContent(module.Metadata.Name),
			Path:                       escapeGoContent(module.Spec.Menu.Path),
			DisplayName:                escapeGoContent(module.Spec.Menu.DisplayName),
			DisplayNameEn:              escapeGoContent(module.Spec.Menu.DisplayNameEn),
			Icon:                       escapeGoContent(module.Spec.Menu.Icon),
			Parent:                     escapeGoContent(module.Spec.Menu.Parent),
			ParentName:                 escapeGoContent(menuNameFromPath(module.Spec.Menu.Parent)),
			ParentDisplayNameEnLiteral: jsLiteral(module.Spec.Menu.ParentDisplayNameEn),
			Order:                      module.Spec.Menu.Order,
			Hidden:                     module.Spec.Menu.Hidden,
		},
	}
	if data.SourceSpec == "" {
		data.SourceSpec = "module.yaml"
	}

	primarySearchAssigned := false
	for _, field := range module.Spec.Entity.Fields {
		mapped, err := mapField(module, field)
		if err != nil {
			return templateData{}, err
		}
		if field.Searchable && !field.UI.Hidden && !primarySearchAssigned {
			mapped.PrimarySearch = true
			primarySearchAssigned = true
		}
		data.Fields = append(data.Fields, mapped)
		if field.Type == "string" || field.Type == "enum" {
			data.HasTextFields = true
		}
		if field.Validation.Pattern != "" {
			data.NeedsRegexp = true
		}
		if field.Validation.Format == "email" {
			data.NeedsEmail = true
		}
		if field.Searchable {
			data.SearchFields = append(data.SearchFields, mapped)
		}
		if mapped.Form {
			switch field.UI.Component {
			case "select":
				data.HasFormSelect = true
			case "switch":
				data.HasFormSwitch = true
			default:
				data.HasFormText = true
			}
		}
		if field.Filterable {
			data.FilterFields = append(data.FilterFields, mapped)
		}
		if field.Sortable {
			data.SortFields = append(data.SortFields, mapped)
			if data.PrimarySortName == "" {
				data.PrimarySortName = field.Name
			}
		}
		if mapped.List {
			data.ListFields = append(data.ListFields, mapped)
		}
		if field.Unique {
			if !data.HasUniqueFields {
				data.UniqueField = mapped
			}
			if !field.Immutable && !data.HasMutableUnique {
				data.HasMutableUnique = true
				data.MutableUniqueField = mapped
			}
			data.HasUniqueFields = true
		}
		if !data.HasUpdateField && !field.Immutable && (field.Type == "string") && !field.Unique && field.Validation.Pattern == "" && field.Validation.Format == "" {
			data.HasUpdateField = true
			data.UpdateField = mapped
			data.HasE2EUpdateField = true
			data.E2EUpdateField = mapped
		} else if !data.HasE2EUpdateField && !field.Immutable && mapped.Form {
			data.HasE2EUpdateField = true
			data.E2EUpdateField = mapped
		}
		if !data.HasV6E2EUpdateField && !field.Immutable && mapped.Form && mapped.List && contains([]string{"string", "text"}, field.Type) {
			data.HasV6E2EUpdateField = true
			data.V6E2EUpdateField = mapped
		}
		if !data.HasE2EMarkerField && field.Unique && field.Searchable && mapped.Form && mapped.List && contains([]string{"string", "text"}, field.Type) {
			data.HasE2EMarkerField = true
			data.E2EMarkerField = mapped
		}
		if !data.HasSearchField && field.Searchable {
			data.HasSearchField = true
			data.SearchField = mapped
		}
	}
	defaultRoleSet := make(map[string]struct{})
	for _, permission := range module.Spec.Permissions {
		defaultRoles := append([]string(nil), permission.DefaultRoles...)
		data.Permissions = append(data.Permissions, permissionData{
			Action:        permission.Action,
			Identifier:    spec.PascalCase(permission.Action),
			Code:          escapeGoContent(module.PermissionCode(permission.Action)),
			DisplayName:   escapeGoContent(permission.DisplayName),
			Description:   escapeGoContent(permission.Description),
			DefaultRoles:  defaultRoles,
			ComponentPath: strings.TrimSuffix(module.Spec.Menu.Path, "/") + "/permissions/" + permission.Action,
		})
		componentPath := strings.TrimSuffix(module.Spec.Menu.Path, "/") + "/permissions/" + permission.Action
		switch permission.Action {
		case "list":
			data.PermissionListPath = componentPath
		case "read":
			data.PermissionReadPath = componentPath
		case "create":
			data.PermissionCreatePath = componentPath
		case "update":
			data.PermissionUpdatePath = componentPath
		case "delete":
			data.PermissionDeletePath = componentPath
		case "export":
			data.PermissionExportPath = componentPath
		}
		for _, role := range defaultRoles {
			defaultRoleSet[role] = struct{}{}
		}
	}
	for role := range defaultRoleSet {
		data.DefaultRoles = append(data.DefaultRoles, role)
	}
	sort.Strings(data.DefaultRoles)
	if permission, ok := module.Permission("list"); ok {
		data.MenuPermissionCode = module.PermissionCode(permission.Action)
		data.MenuDefaultRoles = append([]string(nil), permission.DefaultRoles...)
	} else if permission, ok := module.Permission("read"); ok {
		data.MenuPermissionCode = module.PermissionCode(permission.Action)
		data.MenuDefaultRoles = append([]string(nil), permission.DefaultRoles...)
	} else if len(module.Spec.Permissions) > 0 {
		data.MenuPermissionCode = module.PermissionCode(module.Spec.Permissions[0].Action)
		data.MenuDefaultRoles = append([]string(nil), module.Spec.Permissions[0].DefaultRoles...)
	}
	data.Operations = buildOperations(module)
	for _, role := range data.DefaultRoles {
		for _, operation := range data.Operations {
			data.AuthorizationMatrix = append(data.AuthorizationMatrix, authorizationMatrixData{
				Role:                 role,
				Operation:            operation.Name,
				Method:               operation.Method,
				PolicyPath:           operation.PolicyPath,
				PermissionIdentifier: operation.PermissionIdentifier,
				Allowed:              contains(operation.DefaultRoles, role),
			})
		}
	}
	for _, operation := range data.Operations {
		switch operation.Name {
		case "list":
			data.HasList = true
		case "get":
			data.HasGet = true
		case "create":
			data.HasCreate = true
		case "update":
			data.HasUpdate = true
		case "delete":
			data.HasDelete = true
		case "export":
			data.HasExport = true
		}
	}
	for _, event := range module.Spec.Events {
		data.Events = append(data.Events, eventData{
			Name:     event.Name,
			NameGo:   strconv.Quote(event.Name),
			When:     event.When,
			TypeName: module.Spec.Entity.GoName + spec.PascalCase(event.When) + "Event",
		})
		if event.When == "created" {
			data.CreatedEventName = event.Name
			data.HasCreatedEvent = true
		}
		if event.When == "updated" {
			data.UpdatedEventName = event.Name
			data.HasUpdatedEvent = true
		}
	}
	data.Indexes = buildIndexData(module)
	data.UniqueGroups = buildUniqueGroupData(module, data.Fields)
	if len(data.UniqueGroups) > 0 {
		data.HasUniqueFields = true
	}
	for _, field := range module.Spec.Entity.Fields {
		if field.Type == "enum" {
			values := make([]string, 0, len(field.EnumValues))
			sqliteValues := make([]string, 0, len(field.EnumValues))
			postgresValues := make([]string, 0, len(field.EnumValues))
			mysqlValues := make([]string, 0, len(field.EnumValues))
			for _, value := range field.EnumValues {
				values = append(values, value.Value)
				sqliteValues = append(sqliteValues, sqlLiteral(value.Value, "sqlite"))
				postgresValues = append(postgresValues, sqlLiteral(value.Value, "postgres")+"::character varying")
				mysqlValues = append(mysqlValues, sqlLiteral(value.Value, "mysql"))
			}
			data.Checks = append(data.Checks, checkData{
				Name:           "ck_" + module.Spec.Entity.Table + "_" + field.Column,
				Column:         field.Column,
				Values:         values,
				SQLiteClause:   "CHECK (" + quoteSQLIdentifier(field.Column, "sqlite") + " IN (" + strings.Join(sqliteValues, ", ") + "))",
				PostgresClause: "CHECK (((" + quoteSQLIdentifier(field.Column, "postgres") + ")::text = ANY ((ARRAY[" + strings.Join(postgresValues, ", ") + "])::text[])))",
				MySQLClause:    "(" + quoteSQLIdentifier(field.Column, "mysql") + " IN (" + strings.Join(mysqlValues, ", ") + "))",
			})
		}
	}
	data.MigrationColumns = buildMigrationColumnData(module)
	data.CreateTableSQLite = buildCreateTableDDL(module, "sqlite")
	data.CreateTablePostgres = buildCreateTableDDL(module, "postgres")
	data.CreateTableMySQL = buildCreateTableDDL(module, "mysql")
	return data, nil
}

