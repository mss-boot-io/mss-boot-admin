type localeEntry struct {
	key   string
	value string
}

func renderLocaleRegistry(modules []*spec.Module, locale, frontendRevision string) []byte {
	entries := make([]localeEntry, 0, len(modules)*32)
	for _, module := range modules {
		entries = append(entries, moduleLocaleEntries(module, locale)...)
	}
	sort.SliceStable(entries, func(i, j int) bool { return entries[i].key < entries[j].key })
	var output strings.Builder
	output.WriteString("// Code generated by mss module template " + frontendRevision + " sync. DO NOT EDIT.\n\n")
	output.WriteString("export default {\n")
	for _, entry := range entries {
		fmt.Fprintf(&output, "  %s: %s,\n", strconv.Quote(entry.key), strconv.Quote(entry.value))
	}
	output.WriteString("};\n")
	return []byte(output.String())
}

