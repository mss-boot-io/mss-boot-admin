func titleWords(value string) string {
	words := strings.Fields(strings.ReplaceAll(spec.SnakeCase(value), "_", " "))
	for index := range words {
		words[index] = strings.ToUpper(words[index][:1]) + words[index][1:]
	}
	return strings.Join(words, " ")
}

func menuNameFromPath(path string) string {
	return strings.ReplaceAll(strings.Trim(path, "/"), "/", ".")
}

func discoverModules(repository *os.Root, current *spec.Module, layout targetLayout) ([]*spec.Module, error) {
	byName := map[string]*spec.Module{current.Metadata.Name: current}
	generatedPattern := filepath.ToSlash(filepath.Join(filepath.FromSlash(layout.ModulesDir), "*", "module.yaml"))
	matches, err := fs.Glob(repository.FS(), generatedPattern)
	if err != nil {
		return nil, fmt.Errorf("discover module specs: %w", err)
	}
	currentGeneratedSpec := filepath.ToSlash(filepath.Join(filepath.FromSlash(layout.ModulesDir), current.Metadata.Name, "module.yaml"))
	for _, match := range matches {
		if filepath.ToSlash(match) == currentGeneratedSpec {
			continue
		}
		content, readErr := repository.ReadFile(filepath.FromSlash(match))
		if readErr != nil {
			return nil, fmt.Errorf("read generated module spec %s: %w", match, readErr)
		}
		module, loadErr := spec.ParseModule(content, match)
		if loadErr != nil {
			return nil, loadErr
		}
		byName[module.Metadata.Name] = module
	}
	modules := make([]*spec.Module, 0, len(byName))
	for _, module := range byName {
		modules = append(modules, module)
	}
	sort.SliceStable(modules, func(i, j int) bool {
		return modules[i].Metadata.Name < modules[j].Metadata.Name
	})
	return modules, nil
}

var (
	migrationFilenamePattern  = regexp.MustCompile(`^(?:0|[1-9][0-9]*)(?:_.*)?\.go$`)
	migrationLiteralIDPattern = regexp.MustCompile(`"((?:0|[1-9][0-9]*))"`)
)

func validateMigrationIDUniqueness(repository *os.Root, current *spec.Module, layout targetLayout) error {
	type owner struct {
		key  string
		path string
	}
	owners := make(map[string]owner)
	targetIDs := map[string]struct{}{
		current.Spec.Generation.MigrationID:              {},
		current.Spec.Generation.AuthorizationMigrationID: {},
	}
	register := func(id string, candidate owner) error {
		if id == "" {
			return nil
		}
		if _, targeted := targetIDs[id]; !targeted {
			return nil
		}
		if existing, ok := owners[id]; ok {
			if existing.key == candidate.key {
				return nil
			}
			return &MigrationIDCollisionError{ID: id, Existing: existing.path, Current: candidate.path}
		}
		owners[id] = candidate
		return nil
	}
	currentOwner := owner{key: "module:" + current.Metadata.Name, path: filepath.ToSlash(current.SourcePath)}
	if currentOwner.path == "" {
		currentOwner.path = "module:" + current.Metadata.Name
	}
	if err := register(current.Spec.Generation.MigrationID, currentOwner); err != nil {
		return err
	}
	if err := register(current.Spec.Generation.AuthorizationMigrationID, currentOwner); err != nil {
		return err
	}

	seenPaths := make(map[string]struct{})
	currentGeneratedSpec := filepath.ToSlash(filepath.Join(filepath.FromSlash(layout.ModulesDir), current.Metadata.Name, "module.yaml"))
	sourcePattern := filepath.ToSlash(filepath.Join(filepath.FromSlash(layout.SpecificationsDir), "modules", "*.yaml"))
	generatedPattern := filepath.ToSlash(filepath.Join(filepath.FromSlash(layout.ModulesDir), "*", "module.yaml"))
	for _, pattern := range []string{sourcePattern, generatedPattern} {
		matches, err := fs.Glob(repository.FS(), pattern)
		if err != nil {
			return fmt.Errorf("discover migration IDs from %s: %w", pattern, err)
		}
		for _, match := range matches {
			// The generated module spec is replaced by this run. Skip its stale
			// pre-projection shape while still registering the validated source
			// module above as the owner of both migration identities.
			if filepath.ToSlash(match) == currentGeneratedSpec {
				continue
			}
			if _, seen := seenPaths[match]; seen {
				continue
			}
			seenPaths[match] = struct{}{}
			content, err := repository.ReadFile(filepath.FromSlash(match))
			if err != nil {
				return fmt.Errorf("read module migration identity %s: %w", match, err)
			}
			module, err := spec.ParseModule(content, match)
			if err != nil {
				return err
			}
			if err := register(module.Spec.Generation.MigrationID, owner{
				key:  "module:" + module.Metadata.Name,
				path: match,
			}); err != nil {
				return err
			}
			if err := register(module.Spec.Generation.AuthorizationMigrationID, owner{
				key:  "module:" + module.Metadata.Name,
				path: match,
			}); err != nil {
				return err
			}
		}
	}

	migrationRoot := layout.LegacyMigrationDir
	if migrationRoot == "" {
		return nil
	}
	if _, err := repository.Stat(filepath.FromSlash(migrationRoot)); errors.Is(err, os.ErrNotExist) {
		return nil
	} else if err != nil {
		return fmt.Errorf("inspect Admin migration root: %w", err)
	}
	return fs.WalkDir(repository.FS(), migrationRoot, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() || strings.HasSuffix(entry.Name(), "_test.go") || filepath.Ext(entry.Name()) != ".go" {
			return nil
		}
		candidateOwner := owner{key: "migration:" + path, path: path}
		if migrationFilenamePattern.MatchString(entry.Name()) {
			id, _, _ := strings.Cut(strings.TrimSuffix(entry.Name(), filepath.Ext(entry.Name())), "_")
			if err := register(id, candidateOwner); err != nil {
				return err
			}
		}
		content, err := repository.ReadFile(filepath.FromSlash(path))
		if err != nil {
			return fmt.Errorf("read Admin migration identity %s: %w", path, err)
		}
		// Compatibility migrations may need to query the ledger identity owned by
		// one generated module without claiming that identity. The explicit,
		// module-scoped marker keeps that reference auditable and only suppresses
		// collision ownership while regenerating the named module.
		referenceMarker := []byte("mss:migration-reference " + current.Metadata.Name)
		for _, line := range bytes.Split(content, []byte("\n")) {
			if bytes.Contains(line, referenceMarker) {
				continue
			}
			for _, match := range migrationLiteralIDPattern.FindAllSubmatch(line, -1) {
				if err := register(string(match[1]), candidateOwner); err != nil {
					return err
				}
			}
		}
		return nil
	})
}

func renderLocales(modules []*spec.Module) (string, string) {
	var zhCN strings.Builder
	var enUS strings.Builder
	zhCN.WriteString("// Code generated by mss module sync. DO NOT EDIT.\n\nexport default {\n")
	enUS.WriteString("// Code generated by mss module sync. DO NOT EDIT.\n\nexport default {\n")
	for _, module := range modules {
		key := "menu." + module.Metadata.Name
		fmt.Fprintf(&zhCN, "  %s: %s,\n", tsQuote(key), tsQuote(module.Spec.Menu.DisplayName))
		englishName := module.Spec.Menu.DisplayNameEn
		if englishName == "" {
			englishName = module.Metadata.DisplayName
		}
		fmt.Fprintf(&enUS, "  %s: %s,\n", tsQuote(key), tsQuote(englishName))
		for _, field := range module.Spec.Entity.Fields {
			fieldKey := "module." + module.Metadata.Name + ".field." + field.Name
			fmt.Fprintf(&zhCN, "  %s: %s,\n", tsQuote(fieldKey), tsQuote(field.DisplayName))
			fmt.Fprintf(&enUS, "  %s: %s,\n", tsQuote(fieldKey), tsQuote(field.DisplayName))
		}
	}
	zhCN.WriteString("};\n")
	enUS.WriteString("};\n")
	return zhCN.String(), enUS.String()
}

func compareOutput(repository *os.Root, candidate output) (Change, error) {
	relative, err := rootedName(candidate.path)
	if err != nil {
		return Change{}, err
	}
	action := ActionCreate
	existing, readErr := repository.ReadFile(relative)
	if readErr == nil {
		if candidate.managed && !bytes.Contains(existing, []byte(generatedMarker)) {
			return Change{}, &ConflictError{Path: filepath.ToSlash(candidate.path)}
		}
		action = ActionUpdate
		if bytes.Equal(normalizeNewline(existing), normalizeNewline(candidate.content)) {
			action = ActionUnchanged
		}
	} else if !errors.Is(readErr, os.ErrNotExist) {
		return Change{}, fmt.Errorf("read existing output %s: %w", candidate.path, readErr)
	}
	digest := sha256.Sum256(candidate.content)
	return Change{
		Path:     filepath.ToSlash(candidate.path),
		Action:   action,
		Managed:  candidate.managed,
		Bytes:    len(candidate.content),
		SHA256:   hex.EncodeToString(digest[:]),
		Source:   candidate.source,
		content:  candidate.content,
		fileMode: candidate.fileMode,
	}, nil
}

func compareObsoleteOutput(repository *os.Root, path string) (Change, bool, error) {
	relative, err := rootedName(path)
	if err != nil {
		return Change{}, false, err
	}
	existing, err := repository.ReadFile(relative)
	if errors.Is(err, os.ErrNotExist) {
		return Change{}, false, nil
	}
	if err != nil {
		return Change{}, false, fmt.Errorf("read obsolete generated output %s: %w", path, err)
	}
	if !bytes.Contains(existing, []byte(generatedMarker)) {
		return Change{}, false, &ConflictError{Path: filepath.ToSlash(path)}
	}
	digest := sha256.Sum256(existing)
	return Change{
		Path:    filepath.ToSlash(path),
		Action:  ActionDelete,
		Managed: true,
		Bytes:   len(existing),
		SHA256:  hex.EncodeToString(digest[:]),
		Source:  "obsolete generated output",
	}, true, nil
}

func writeAtomic(repository *os.Root, change Change) error {
	relative, err := rootedName(change.Path)
	if err != nil {
		return err
	}
	if change.Action == ActionDelete {
		existing, readErr := repository.ReadFile(relative)
		if errors.Is(readErr, os.ErrNotExist) {
			return nil
		}
		if readErr != nil {
			return fmt.Errorf("read obsolete generated output %s before delete: %w", change.Path, readErr)
		}
		if !bytes.Contains(existing, []byte(generatedMarker)) {
			return &ConflictError{Path: change.Path}
		}
		if err := repository.Remove(relative); err != nil {
			return fmt.Errorf("delete obsolete generated output %s: %w", change.Path, err)
		}
		return nil
	}
	directory := filepath.Dir(relative)
	if directory != "." {
		if err := repository.MkdirAll(directory, 0o755); err != nil {
			return fmt.Errorf("create output directory for %s: %w", change.Path, err)
		}
	}
	mode := change.fileMode
	if mode == 0 {
		mode = 0o644
	}
	temporary, temporaryName, err := createRootTemp(repository, directory, mode)
	if err != nil {
		return fmt.Errorf("create temporary output for %s: %w", change.Path, err)
	}
	cleanup := func() {
		_ = temporary.Close()
		_ = repository.Remove(temporaryName)
	}
	if _, err := temporary.Write(change.content); err != nil {
		cleanup()
		return fmt.Errorf("write temporary output for %s: %w", change.Path, err)
	}
	if err := temporary.Chmod(mode); err != nil {
		cleanup()
		return fmt.Errorf("chmod temporary output for %s: %w", change.Path, err)
	}
	if err := temporary.Sync(); err != nil {
		cleanup()
		return fmt.Errorf("sync temporary output for %s: %w", change.Path, err)
	}
	if err := temporary.Close(); err != nil {
		cleanup()
		return fmt.Errorf("close temporary output for %s: %w", change.Path, err)
	}
	if err := repository.Rename(temporaryName, relative); err != nil {
		cleanup()
		return fmt.Errorf("replace output %s: %w", change.Path, err)
	}
	return nil
}

func createRootTemp(repository *os.Root, directory string, mode os.FileMode) (*os.File, string, error) {
	for attempt := 0; attempt < 100; attempt++ {
		var entropy [12]byte
		if _, err := rand.Read(entropy[:]); err != nil {
			return nil, "", err
		}
		name := ".mss-generate-" + hex.EncodeToString(entropy[:])
		if directory != "." {
			name = filepath.Join(directory, name)
		}
		file, err := repository.OpenFile(name, os.O_RDWR|os.O_CREATE|os.O_EXCL, mode)
		if err == nil {
			return file, name, nil
		}
		if !errors.Is(err, os.ErrExist) {
			return nil, "", err
		}
	}
	return nil, "", errors.New("temporary output name collision limit exceeded")
}

func renderTemplate(path string, data templateData) ([]byte, error) {
	relative, err := rootedName(path)
	if err != nil {
		return nil, err
	}
	embeddedPath := filepath.ToSlash(relative)
	embeddedPath = strings.TrimPrefix(embeddedPath, "templates/")
	content, err := foundationtemplates.Module.ReadFile(embeddedPath)
	if err != nil {
		return nil, fmt.Errorf("read generator template %s: %w", path, err)
	}
	parsed, err := template.New(filepath.Base(path)).Option("missingkey=error").Parse(string(content))
	if err != nil {
		return nil, fmt.Errorf("parse generator template %s: %w", path, err)
	}
	var buffer bytes.Buffer
	if err := parsed.Execute(&buffer, data); err != nil {
		return nil, fmt.Errorf("execute generator template %s: %w", path, err)
	}
	return buffer.Bytes(), nil
}

func rootedName(relative string) (string, error) {
	if filepath.IsAbs(relative) {
		return "", fmt.Errorf("output path %q must be repository-relative", relative)
	}
	cleaned := filepath.Clean(filepath.FromSlash(relative))
	if cleaned == "." || cleaned == ".." || strings.HasPrefix(cleaned, ".."+string(filepath.Separator)) {
		return "", fmt.Errorf("output path %q escapes repository root", relative)
	}
	return cleaned, nil
}

func canonicalModuleSourcePath(repository *os.Root, repositoryPath, sourcePath string) (string, error) {
	if strings.TrimSpace(sourcePath) == "" {
		return "module.yaml", nil
	}
	rootAbsolute, err := filepath.Abs(repositoryPath)
	if err != nil {
		return "", fmt.Errorf("resolve repository root for module source: %w", err)
	}
	rootResolved, err := filepath.EvalSymlinks(rootAbsolute)
	if err != nil {
		return "", fmt.Errorf("resolve repository root for module source: %w", err)
	}

	var relative string
	if filepath.IsAbs(sourcePath) {
		sourceAbsolute := filepath.Clean(sourcePath)
		if sourceResolved, resolveErr := filepath.EvalSymlinks(sourceAbsolute); resolveErr == nil {
			relative, err = filepath.Rel(rootResolved, sourceResolved)
		} else {
			relative, err = filepath.Rel(rootAbsolute, sourceAbsolute)
		}
		if err != nil {
			return "", fmt.Errorf("resolve module source %q: %w", sourcePath, err)
		}
	} else {
		relative, err = rootedName(sourcePath)
		if err != nil {
			return "", fmt.Errorf("confine module source: %w", err)
		}
	}
	if relative == "." || relative == ".." || strings.HasPrefix(relative, ".."+string(filepath.Separator)) || filepath.IsAbs(relative) {
		return "", fmt.Errorf("module source %q is outside the repository root", sourcePath)
	}
	relative, err = rootedName(relative)
	if err != nil {
		return "", fmt.Errorf("confine module source: %w", err)
	}
	info, statErr := repository.Stat(relative)
	if statErr == nil {
		if !info.Mode().IsRegular() {
			return "", fmt.Errorf("module source %q is not a regular repository file", sourcePath)
		}
	} else if !errors.Is(statErr, os.ErrNotExist) {
		return "", fmt.Errorf("module source %q escapes or cannot be inspected within the repository: %w", sourcePath, statErr)
	}
	return filepath.ToSlash(relative), nil
}

func renderColumns(module *spec.Module) string {
	var builder strings.Builder
	for _, field := range module.Spec.Entity.Fields {
		if field.List != nil && !*field.List {
			continue
		}
		fmt.Fprintf(&builder, "    {\n")
		fmt.Fprintf(&builder, "      title: intl.formatMessage({ id: %s, defaultMessage: %s }),\n",
			tsQuote("module."+module.Metadata.Name+".field."+field.Name), tsQuote(field.DisplayName))
		fmt.Fprintf(&builder, "      dataIndex: %s,\n", tsQuote(field.Name))
		if !field.Searchable && !field.Filterable {
			builder.WriteString("      hideInSearch: true,\n")
		}
		switch field.Type {
		case "bool":
			builder.WriteString("      valueType: 'switch',\n")
		case "date":
			builder.WriteString("      valueType: 'date',\n")
		case "datetime":
			builder.WriteString("      valueType: 'dateTime',\n")
		case "decimal":
			builder.WriteString("      valueType: 'money',\n")
		case "enum":
			builder.WriteString("      valueEnum: {\n")
			for _, value := range field.EnumValues {
				fmt.Fprintf(&builder, "        %s: { text: %s%s },\n", tsQuote(value.Value), tsQuote(value.Label), enumColor(value.Color))
			}
			builder.WriteString("      },\n")
		}
		if width, ok := numericWidth(field.UI.Width); ok {
			fmt.Fprintf(&builder, "      width: %d,\n", width)
		}
		builder.WriteString("    },\n")
	}
	return builder.String()
}

func renderFormFields(module *spec.Module) string {
	var builder strings.Builder
	for _, field := range module.Spec.Entity.Fields {
		if field.Form != nil && !*field.Form {
			continue
		}
		component := formComponent(field)
		fmt.Fprintf(&builder, "        <%s\n", component)
		fmt.Fprintf(&builder, "          name=%s\n", tsQuote(field.Name))
		fmt.Fprintf(&builder, "          label={intl.formatMessage({ id: %s, defaultMessage: %s })}\n",
			tsQuote("module."+module.Metadata.Name+".field."+field.Name), tsQuote(field.DisplayName))
		if field.Required {
			builder.WriteString("          rules={[{ required: true }]}\n")
		}
		if field.Immutable {
			builder.WriteString("          disabled={Boolean(current?.id)}\n")
		}
		if field.Type == "enum" {
			builder.WriteString("          options={[\n")
			for _, value := range field.EnumValues {
				fmt.Fprintf(&builder, "            { label: %s, value: %s },\n", tsQuote(value.Label), tsQuote(value.Value))
			}
			builder.WriteString("          ]}\n")
		}
		builder.WriteString("        />\n")
	}
	return builder.String()
}

func formComponent(field spec.FieldSpec) string {
	if field.UI.Component != "" {
		switch field.UI.Component {
		case "textarea", "json-editor":
			return "ProFormTextArea"
		case "number", "money":
			return "ProFormDigit"
		case "select", "radio", "checkbox", "relation-select":
			return "ProFormSelect"
		case "switch":
			return "ProFormSwitch"
		case "date":
			return "ProFormDatePicker"
		case "datetime":
			return "ProFormDateTimePicker"
		default:
			return "ProFormText"
		}
	}
	switch field.Type {
	case "text", "json", "files":
		return "ProFormTextArea"
	case "int", "int64", "uint", "float64", "decimal":
		return "ProFormDigit"
	case "enum", "relation":
		return "ProFormSelect"
	case "bool":
		return "ProFormSwitch"
	case "date":
		return "ProFormDatePicker"
	case "datetime":
		return "ProFormDateTimePicker"
	default:
		return "ProFormText"
	}
}

func enumColor(color string) string {
	if color == "" {
		return ""
	}
	return ", status: " + tsQuote(color)
}

func numericWidth(value any) (int, bool) {
	switch typed := value.(type) {
	case int:
		return typed, true
	case int64:
		return int(typed), true
	case float64:
		return int(typed), true
	case string:
		width, err := strconv.Atoi(typed)
		return width, err == nil
	default:
		return 0, false
	}
}

func normalizeNewline(content []byte) []byte {
	normalized := bytes.ReplaceAll(content, []byte("\r\n"), []byte("\n"))
	normalized = bytes.TrimRight(normalized, "\n")
	return append(normalized, '\n')
}

func sanitizeTagValue(value string) string {
	value = strings.ReplaceAll(value, ";", ",")
	value = strings.ReplaceAll(value, "`", "'")
	value = strings.ReplaceAll(value, "\n", " ")
	return strings.TrimSpace(value)
}

func escapeGoContent(value string) string {
	quoted := strconv.Quote(value)
	if len(quoted) >= 2 {
		return quoted[1 : len(quoted)-1]
	}
	return value
}

func tsQuote(value string) string {
	value = strings.ReplaceAll(value, "\\", "\\\\")
	value = strings.ReplaceAll(value, "'", "\\'")
	value = strings.ReplaceAll(value, "\r", "")
	value = strings.ReplaceAll(value, "\n", "\\n")
	return "'" + value + "'"
}

func numberString(value float64) string {
	return strconv.FormatFloat(value, 'f', -1, 64)
}

func yesNo(value bool) string {
	if value {
		return "是"
	}
	return "否"
}

func contains(values []string, target string) bool {
	for _, value := range values {
		if value == target {
			return true
		}
	}
	return false
}
