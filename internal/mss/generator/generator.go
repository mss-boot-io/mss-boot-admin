func fixtureGo(field spec.FieldSpec, alternate bool) string {
	if field.Type == "bool" {
		if alternate {
			return "false"
		}
		return "true"
	}
	if field.Type == "enum" && len(field.EnumValues) > 0 {
		index := 0
		if alternate && len(field.EnumValues) > 1 {
			index = 1
		}
		return strconv.Quote(field.EnumValues[index].Value)
	}
	if field.Validation.Format == "email" {
		if alternate {
			return strconv.Quote("alternate@example.test")
		}
		return strconv.Quote("supplier@example.test")
	}
	candidates := []string{"VALUE_01", "value", "sample", "AA"}
	if alternate {
		candidates = []string{"VALUE_02", "value two", "alternate", "BB"}
	}
	minimum := 0
	if field.Validation.MinLength != nil {
		minimum = *field.Validation.MinLength
	}
	maximum := 0
	if field.Validation.MaxLength != nil {
		maximum = *field.Validation.MaxLength
	}
	var pattern *regexp.Regexp
	if field.Validation.Pattern != "" {
		pattern = regexp.MustCompile(field.Validation.Pattern)
	}
	for _, candidate := range candidates {
		for len([]rune(candidate)) < minimum {
			candidate += "A"
		}
		if maximum > 0 && len([]rune(candidate)) > maximum {
			candidate = string([]rune(candidate)[:maximum])
		}
		if pattern == nil || pattern.MatchString(candidate) {
			return strconv.Quote(candidate)
		}
	}
	return strconv.Quote(strings.Repeat("A", max(1, minimum)))
}

func databaseType(field spec.FieldSpec) string {
	maxLength := 255
	if field.Validation.MaxLength != nil {
		maxLength = *field.Validation.MaxLength
	}
	switch field.Type {
	case "string", "enum", "uuid", "file", "relation":
		return fmt.Sprintf("varchar(%d)", maxLength)
	case "text", "files":
		return "text"
	case "json":
		return "json"
	case "int":
		return "int"
	case "int64":
		return "bigint"
	case "uint":
		return "bigint unsigned"
	case "float64":
		return "double"
	case "decimal":
		precision, scale := 18, 2
		if field.Validation.Precision != nil {
			precision = *field.Validation.Precision
		}
		if field.Validation.Scale != nil {
			scale = *field.Validation.Scale
		}
		return fmt.Sprintf("decimal(%d,%d)", precision, scale)
	case "bool":
		return "boolean"
	case "date":
		return "date"
	case "datetime":
		return "datetime"
	default:
		return "text"
	}
}

func buildBindingTag(field spec.FieldSpec) string {
	var rules []string
	if field.Required {
		rules = append(rules, "required")
	}
	if field.Validation.Format == "email" {
		rules = append(rules, "email")
	}
	if field.Validation.MinLength != nil {
		rules = append(rules, "min="+strconv.Itoa(*field.Validation.MinLength))
	}
	if field.Validation.MaxLength != nil {
		rules = append(rules, "max="+strconv.Itoa(*field.Validation.MaxLength))
	}
	if field.Validation.Minimum != nil {
		rules = append(rules, "gte="+numberString(*field.Validation.Minimum))
	}
	if field.Validation.Maximum != nil {
		rules = append(rules, "lte="+numberString(*field.Validation.Maximum))
	}
	return strings.Join(rules, ",")
}

