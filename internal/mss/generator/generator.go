func buildIndexData(module *spec.Module) []indexData {
	type indexDefinition struct {
		name    string
		columns []string
		unique  bool
	}
	definitions := make([]indexDefinition, 0, len(module.Spec.Entity.Indexes)+len(module.Spec.Entity.Fields)+1)
	definitions = append(definitions, indexDefinition{
		name:    "idx_" + module.Spec.Entity.Table + "_deleted_at",
		columns: []string{"deleted_at"},
	})
	for _, field := range module.Spec.Entity.Fields {
		if field.Unique {
			definitions = append(definitions, indexDefinition{
				name:    "ux_" + module.Spec.Entity.Table + "_" + field.Column,
				columns: []string{field.Column},
				unique:  true,
			})
		} else if field.Index {
			definitions = append(definitions, indexDefinition{
				name:    "idx_" + module.Spec.Entity.Table + "_" + field.Column,
				columns: []string{field.Column},
			})
		}
	}
	for _, databaseIndex := range module.Spec.Entity.Indexes {
		columns := make([]string, 0, len(databaseIndex.Fields))
		for _, fieldName := range databaseIndex.Fields {
			field, _ := module.Field(fieldName)
			columns = append(columns, field.Column)
		}
		definitions = append(definitions, indexDefinition{
			name:    databaseIndex.Name,
			columns: columns,
			unique:  databaseIndex.Unique,
		})
	}
	sort.SliceStable(definitions, func(i, j int) bool { return definitions[i].name < definitions[j].name })
	indexes := make([]indexData, 0, len(definitions))
	for _, definition := range definitions {
		indexes = append(indexes, indexData{
			Name:        definition.name,
			Unique:      definition.unique,
			Columns:     append([]string(nil), definition.columns...),
			SQLiteDDL:   buildIndexDDL(module.Spec.Entity.Table, definition.name, definition.columns, definition.unique, "sqlite"),
			PostgresDDL: buildIndexDDL(module.Spec.Entity.Table, definition.name, definition.columns, definition.unique, "postgres"),
			MySQLDDL:    buildIndexDDL(module.Spec.Entity.Table, definition.name, definition.columns, definition.unique, "mysql"),
		})
	}
	return indexes
}

func buildUniqueGroupData(module *spec.Module, fields []fieldData) []uniqueGroupData {
	byName := make(map[string]fieldData, len(fields))
	for index, field := range module.Spec.Entity.Fields {
		byName[field.Name] = fields[index]
	}
	groups := make([]uniqueGroupData, 0)
	for _, field := range module.Spec.Entity.Fields {
		if field.Unique {
			groups = append(groups, uniqueGroupData{
				Name:   "ux_" + module.Spec.Entity.Table + "_" + field.Column,
				Fields: []fieldData{byName[field.Name]},
			})
		}
	}
	for _, databaseIndex := range module.Spec.Entity.Indexes {
		if !databaseIndex.Unique {
			continue
		}
		group := uniqueGroupData{Name: databaseIndex.Name}
		for _, fieldName := range databaseIndex.Fields {
			group.Fields = append(group.Fields, byName[fieldName])
		}
		groups = append(groups, group)
	}
	sort.SliceStable(groups, func(i, j int) bool { return groups[i].Name < groups[j].Name })
	return groups
}

func buildIndexDDL(table, name string, columns []string, unique bool, dialect string) string {
	quotedColumns := make([]string, 0, len(columns))
	for _, column := range columns {
		quotedColumns = append(quotedColumns, quoteSQLIdentifier(column, dialect))
	}
	uniqueText := ""
	if unique {
		uniqueText = "UNIQUE "
	}
	ifNotExists := " IF NOT EXISTS"
	if dialect == "mysql" {
		ifNotExists = ""
	}
	return "CREATE " + uniqueText + "INDEX" + ifNotExists + " " + quoteSQLIdentifier(name, dialect) +
		" ON " + quoteSQLIdentifier(table, dialect) + " (" + strings.Join(quotedColumns, ", ") + ")"
}

func buildCreateTableDDL(module *spec.Module, dialect string) string {
	columns := []string{
		quoteSQLIdentifier("id", dialect) + " " + ddlStringType(64, dialect) + " NOT NULL PRIMARY KEY",
		quoteSQLIdentifier("created_at", dialect) + " " + ddlTimestampType(dialect) + " NOT NULL",
		quoteSQLIdentifier("updated_at", dialect) + " " + ddlTimestampType(dialect) + " NOT NULL",
		quoteSQLIdentifier("deleted_at", dialect) + " " + ddlTimestampType(dialect) + " NULL",
	}
	constraints := make([]string, 0)
	for _, field := range module.Spec.Entity.Fields {
		definition := quoteSQLIdentifier(field.Column, dialect) + " "
		switch field.Type {
		case "bool":
			definition += "BOOLEAN"
		default:
			length := 255
			if field.Validation.MaxLength != nil {
				length = *field.Validation.MaxLength
			}
			definition += ddlStringType(length, dialect)
		}
		if field.Required && !field.Nullable {
			definition += " NOT NULL"
		}
		if field.Default != nil {
			definition += " DEFAULT " + sqlLiteral(field.Default, dialect)
		}
		columns = append(columns, definition)
		if field.Type == "enum" {
			values := make([]string, 0, len(field.EnumValues))
			for _, enumValue := range field.EnumValues {
				values = append(values, sqlLiteral(enumValue.Value, dialect))
			}
			constraints = append(constraints, "CONSTRAINT "+quoteSQLIdentifier("ck_"+module.Spec.Entity.Table+"_"+field.Column, dialect)+
				" CHECK ("+quoteSQLIdentifier(field.Column, dialect)+" IN ("+strings.Join(values, ", ")+"))")
		}
	}
	columns = append(columns, constraints...)
	statement := "CREATE TABLE IF NOT EXISTS " + quoteSQLIdentifier(module.Spec.Entity.Table, dialect) + " (\n  " +
		strings.Join(columns, ",\n  ") + "\n)"
	if dialect == "mysql" {
		statement += " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin"
	}
	return statement
}

func quoteSQLIdentifier(value, dialect string) string {
	if dialect == "mysql" {
		return "`" + strings.ReplaceAll(value, "`", "``") + "`"
	}
	return `"` + strings.ReplaceAll(value, `"`, `""`) + `"`
}

func ddlStringType(length int, dialect string) string {
	value := fmt.Sprintf("VARCHAR(%d)", length)
	if dialect == "mysql" {
		value += " COLLATE utf8mb4_bin"
	}
	return value
}

func ddlTimestampType(dialect string) string {
	switch dialect {
	case "postgres":
		return "TIMESTAMPTZ"
	case "mysql":
		return "DATETIME(3)"
	default:
		return "DATETIME"
	}
}

func sqlLiteral(value any, dialect string) string {
	switch typed := value.(type) {
	case bool:
		if typed {
			if dialect == "sqlite" {
				return "1"
			}
			return "TRUE"
		}
		if dialect == "sqlite" {
			return "0"
		}
		return "FALSE"
	case string:
		return "'" + strings.ReplaceAll(typed, "'", "''") + "'"
	default:
		return fmt.Sprint(value)
	}
}

func goLiteral(value any) string {
	switch typed := value.(type) {
	case string:
		return strconv.Quote(typed)
	case bool:
		return strconv.FormatBool(typed)
	case nil:
		return ""
	default:
		return fmt.Sprint(value)
	}
}

