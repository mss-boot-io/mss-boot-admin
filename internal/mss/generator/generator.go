// ConflictError prevents the generator from replacing a user-owned file at a
// managed output path. All conflicts are detected before the first write.
type ConflictError struct {
	Path string
}

func (e *ConflictError) Error() string {
	return "generated output conflicts with user-owned file: " + e.Path
}

// MigrationIDCollisionError prevents a module migration from sharing a
// persisted identity with another module or a file-based Admin migration.
// The check runs before output comparison or the first write.
type MigrationIDCollisionError struct {
	ID       string
	Existing string
	Current  string
}

func (e *MigrationIDCollisionError) Error() string {
	return fmt.Sprintf("migration ID %s collides between %s and %s", e.ID, e.Existing, e.Current)
}

