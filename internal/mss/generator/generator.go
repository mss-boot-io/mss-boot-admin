// Action describes how one output differs from the workspace.
type Action string

const (
	ActionCreate    Action = "create"
	ActionDelete    Action = "delete"
	ActionUpdate    Action = "update"
	ActionUnchanged Action = "unchanged"
)

// Options control generation. Dry-run is the default when Write is false.
type Options struct {
	Root           string
	Write          bool
	Check          bool
	FrontendTarget string
	Project        *project.ProjectDocument
}

// Change is one deterministic output decision.
type Change struct {
	Path     string `json:"path"`
	Action   Action `json:"action"`
	Managed  bool   `json:"managed"`
	Bytes    int    `json:"bytes"`
	SHA256   string `json:"sha256"`
	Source   string `json:"source,omitempty"`
	content  []byte
	fileMode os.FileMode
}

// Plan is safe to render for humans or agents before applying writes.
type Plan struct {
	Module           string       `json:"module"`
	GeneratedAt      time.Time    `json:"generatedAt"`
	DryRun           bool         `json:"dryRun"`
	Check            bool         `json:"check"`
	Phase            string       `json:"phase"`
	GeneratorVersion string       `json:"generatorVersion"`
	GeneratorCommit  string       `json:"generatorCommit,omitempty"`
	TemplateRevision string       `json:"templateRevision"`
	FrontendTarget   string       `json:"frontendTarget,omitempty"`
	LayoutKind       string       `json:"layoutKind"`
	Complete         bool         `json:"complete"`
	Projections      []Projection `json:"projections"`
	Changes          []Change     `json:"changes"`
}

// DriftError is returned by --check when generated output is missing or stale.
type DriftError struct {
	Paths []string
}

func (e *DriftError) Error() string {
	return "generated module output is stale: " + strings.Join(e.Paths, ", ")
}

// JSON returns stable indented JSON.
func (p Plan) JSON() ([]byte, error) {
	return json.MarshalIndent(p, "", "  ")
}

// Text returns a compact generation summary.
func (p Plan) Text() string {
	var builder strings.Builder
	fmt.Fprintf(&builder, "mss module generate: %s\n", p.Module)
	fmt.Fprintf(&builder, "dry-run: %t\n", p.DryRun)
	fmt.Fprintf(&builder, "check: %t\n\n", p.Check)
	fmt.Fprintf(&builder, "phase: %s\n", p.Phase)
	fmt.Fprintf(&builder, "generator version: %s\n", p.GeneratorVersion)
	if p.GeneratorCommit != "" {
		fmt.Fprintf(&builder, "generator commit: %s\n", p.GeneratorCommit)
	}
	fmt.Fprintf(&builder, "template revision: %s\n", p.TemplateRevision)
	if p.FrontendTarget != "" {
		fmt.Fprintf(&builder, "frontend target: %s\n", p.FrontendTarget)
	}
	fmt.Fprintf(&builder, "project layout: %s\n", p.LayoutKind)
	fmt.Fprintf(&builder, "complete: %t\n", p.Complete)
	deferred := 0
	for _, projection := range p.Projections {
		if projection.Status == ProjectionDeferred {
			deferred++
		}
	}
	fmt.Fprintf(&builder, "deferred projections: %d\n\n", deferred)
	for _, change := range p.Changes {
		fmt.Fprintf(&builder, "%-9s %s (%d bytes, %s)\n", change.Action, change.Path, change.Bytes, change.SHA256[:12])
	}
	return builder.String()
}

// Generate renders one validated module and optionally writes the plan atomically.
func Generate(module *spec.Module, options Options) (Plan, error) {
	if module == nil {
		return Plan{}, errors.New("module specification is nil")
	}
	if options.Root == "" {
		return Plan{}, errors.New("repository root is required")
	}
	layout, err := resolveTargetLayout(options.Project)
	if err != nil {
		return Plan{}, fmt.Errorf("resolve target project layout: %w", err)
	}
	frontendTarget := strings.TrimSpace(options.FrontendTarget)
	if frontendTarget == "" {
		frontendTarget = spec.FrontendTargetAntDV6
	}
	if frontendTarget != spec.FrontendTargetAntDV6 {
		return Plan{}, fmt.Errorf("unsupported frontend target %q: use %s", frontendTarget, spec.FrontendTargetAntDV6)
	}
	repository, err := os.OpenRoot(options.Root)
	if err != nil {
		return Plan{}, fmt.Errorf("open repository root: %w", err)
	}
	defer repository.Close()
	if issues := module.Validate(); len(issues) > 0 {
		return Plan{}, &spec.ValidationError{Issues: issues}
	}
	plan := Plan{
		Module:           module.Metadata.Name,
		GeneratedAt:      time.Now().UTC(),
		DryRun:           !options.Write,
		Check:            options.Check,
		Phase:            "generated-module-checkpoint",
		GeneratorVersion: buildinfo.VersionString(),
		GeneratorCommit:  buildinfo.CommitString(),
		TemplateRevision: moduleTemplateRevision,
		FrontendTarget:   frontendTarget,
		LayoutKind:       layout.Kind,
		Changes:          make([]Change, 0),
	}
	projections, projectionErr := buildProjectionReport(module)
	plan.Projections = projections
	plan.Complete = true
	for _, projection := range projections {
		if projection.Status == ProjectionDeferred || projection.Status == ProjectionUnsupported {
			plan.Complete = false
		}
	}
	if projectionErr != nil {
		return plan, projectionErr
	}
	if module.Spec.Generation.Frontend != nil && *module.Spec.Generation.Frontend && !module.SupportsFrontendTarget(frontendTarget) {
		return plan, fmt.Errorf("module %s does not declare frontend target %s", module.Metadata.Name, frontendTarget)
	}
	canonicalSource, err := canonicalModuleSourcePath(repository, options.Root, module.SourcePath)
	if err != nil {
		return plan, err
	}
	canonicalModule := *module
	canonicalModule.SourcePath = canonicalSource
	module = &canonicalModule
	if err := validateMigrationIDUniqueness(repository, module, layout); err != nil {
		return plan, err
	}

	data, err := buildTemplateData(module)
	if err != nil {
		return plan, err
	}
	data.TargetModule = layout.TargetModule
	data.AdminModule = layout.AdminModule
	data.FrameworkModule = layout.FrameworkModule
	data.AdminWebPackage = layout.AdminWebPackage
	data.ModuleDirectory = filepath.ToSlash(filepath.Join(layout.ModulesDir, module.Metadata.Name))
	data.BackendDirectory = layout.BackendDir
	backendRelativeModule, relativeErr := filepath.Rel(filepath.FromSlash(layout.BackendDir), filepath.FromSlash(data.ModuleDirectory))
	if relativeErr != nil {
		return plan, fmt.Errorf("resolve backend-relative module directory: %w", relativeErr)
	}
	data.BackendRelativeModuleDirectory = filepath.ToSlash(backendRelativeModule)
	data.FrontendDirectory = layout.FrontendDir
	data.GeneratedDirectory = layout.GeneratedDir
	data.BusinessRoutesFile = layout.BusinessRoutesFile
	data.DocumentationModulesDirectory = layout.DocumentationModulesDir
	if layout.Kind == layoutThinHost {
		data.MSSCommand = "mss --root ."
	} else {
		data.MSSCommand = "go run ./cmd/mss"
	}
	outputs, err := renderModuleOutputs(repository, module, data, frontendTarget, layout)
	if err != nil {
		return plan, err
	}
	registryOutputs, err := renderRegistryOutputs(repository, module, frontendTarget, layout)
	if err != nil {
		return plan, err
	}
	outputs = append(outputs, registryOutputs...)

	plan.Changes = make([]Change, 0, len(outputs))

	for _, output := range outputs {
		change, err := compareOutput(repository, output)
		if err != nil {
			return plan, err
		}
		plan.Changes = append(plan.Changes, change)
	}
	for _, obsoletePath := range obsoleteModuleOutputPaths(module, frontendTarget, layout) {
		change, exists, err := compareObsoleteOutput(repository, obsoletePath)
		if err != nil {
			return plan, err
		}
		if exists {
			plan.Changes = append(plan.Changes, change)
		}
	}
	sort.SliceStable(plan.Changes, func(i, j int) bool {
		return plan.Changes[i].Path < plan.Changes[j].Path
	})

	if options.Check {
		var stale []string
		for _, change := range plan.Changes {
			if change.Action != ActionUnchanged {
				stale = append(stale, change.Path)
			}
		}
		if len(stale) > 0 {
			return plan, &DriftError{Paths: stale}
		}
		return plan, nil
	}

	if options.Write {
		for _, change := range plan.Changes {
			if change.Action == ActionUnchanged {
				continue
			}
			if err := writeAtomic(repository, change); err != nil {
				return plan, err
			}
		}
	}
	return plan, nil
}

